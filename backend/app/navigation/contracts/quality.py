"""Availability and provenance quality metadata without hidden policy."""

from enum import StrEnum

from pydantic import BaseModel, ConfigDict, Field


class AvailabilityStatus(StrEnum):
    AVAILABLE = "AVAILABLE"
    AGING = "AGING"
    STALE = "STALE"
    MISSING = "MISSING"
    CONFLICT = "CONFLICT"
    INVALID = "INVALID"


class DataQuality(StrEnum):
    """Provenance of a value, not a risk score.

    ``REAL`` means read from a real-data file; ``SYNTHETIC`` means generated by
    the deterministic research gap-fill or explicitly marked test fixtures;
    ``MISSING`` means the provider has no value; ``UNKNOWN`` means the value
    exists but its provenance cannot be established.
    """

    REAL = "real"
    SYNTHETIC = "synthetic"
    MISSING = "missing"
    UNKNOWN = "unknown"


class QualityMetadata(BaseModel):
    """Source quality annotation; interpretation is left to later policy layers."""

    model_config = ConfigDict(frozen=True)

    availability: AvailabilityStatus
    data_quality: DataQuality | None = None
    uncertainty: float | None = Field(default=None, ge=0)
    source: str | None = None
    reason: str | None = None


def combine_quality(values: list[DataQuality]) -> DataQuality:
    """Combine component provenance conservatively.

    Any missing/unknown component makes the result unknown for safety; any
    synthetic component makes the aggregate synthetic; otherwise real.
    """
    if not values:
        return DataQuality.UNKNOWN
    if any(value in (DataQuality.MISSING, DataQuality.UNKNOWN) for value in values):
        return DataQuality.UNKNOWN
    if any(value is DataQuality.SYNTHETIC for value in values):
        return DataQuality.SYNTHETIC
    return DataQuality.REAL
